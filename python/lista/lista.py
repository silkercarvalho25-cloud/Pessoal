# Declarando uma lista com elementos iniciais
frutas = ["laranja", "maca", "uva"]
print(frutas)

# Declarando uma lista vazia
frutas = []
print(frutas)

# Criando uma lista a partir de uma string (cada caractere vira um item)
letras = list("python")
print(letras)

# Criando uma lista de números sequenciais usando range
numeros = list(range(10))
print(numeros)

# Criando uma lista com múltiplos tipos de dados (carro)
carro = ["Ferrari", "F8", 4200000, 2020, 2900, "São Paulo", True]
print(carro)

