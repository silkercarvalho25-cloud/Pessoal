# listas podem receber outras listas, virando Listas Aninhadas
matriz = [
    ["a", "b", "c"],
    [1 , 2 , 3],
    ["A1", "B2", "C3"]
          ]
print(matriz[0]) #primeira lista [0]
print(matriz[0][0]) #primeira lista [0], primeiro elemento [0]
print(matriz[1][1]) #segundo elemento [1], segundo elemeto [1]
print(matriz[-1][-1]) #primeiro elemento de tras pra frente [-1], primeiro elemento de tras pra frente [-1]